/** Detect browser language → en | zh | es | ja (fallback en). */
export function detectToolUiLocale(): ToolUiLocale {
  const raw =
    (typeof navigator !== "undefined" &&
      (navigator.language ||
        (navigator as Navigator & { userLanguage?: string }).userLanguage)) ||
    "en";
  const code = raw.slice(0, 2).toLowerCase();
  return TOOL_UI_LOCALES.includes(code as ToolUiLocale)
    ? (code as ToolUiLocale)
    : "en";
}

export function getToolUiMessage(
  locale: ToolUiLocale,
  key: string
): string | undefined {
  return toolUiDictionary[locale]?.[key] ?? toolUiDictionary.en[key];
}

export function isFlatUiKey(key: string): boolean {
  return key in toolUiDictionary.en;
}
